"""Build exact display-name/registry-ID translations; fail when upstream adds a name.

Run from any directory: python tools/localization/generate_names.py [--check]
The English catalog and saved IDs remain unchanged. Edit names.zh-CN.tsv, then
regenerate LocalizationNames.h when updating the upstream loot catalog.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name("names.zh-CN.tsv")
HEADER = ROOT / "VeoxDMA/Misc/LocalizationNames.h"
STRING = r'"((?:[^"\\]|\\.)*)"'


def decode_c_string(value):
    # Catalog octal escapes are individual UTF-8 bytes, not Unicode code points.
    value = re.sub(r"\\([0-7]{1,3})", lambda m: chr(int(m[1], 8)), value)
    if any(0x80 <= ord(c) <= 0xFF for c in value):
        value = value.encode("latin1").decode("utf-8")
    return json.loads('"' + value + '"')


def catalog_rows():
    source = (ROOT / "VeoxDMA/Config/LootFilterData.h").read_text(encoding="utf-8-sig")
    pattern = (r'\{\s*' + STRING + r',\s*' + STRING + r',\s*' + STRING
               + r',\s*Category::(\w+),\s*Rarity::\w+,\s*RobRunWorld::Kind::\w+,\s*' + STRING)
    rows = [tuple(decode_c_string(s) if i != 3 else s for i, s in enumerate(m))
            for m in re.findall(pattern, source)]
    expected = int(re.search(r"// Rows: (\d+)", source)[1])
    if len(rows) != expected:
        raise ValueError(f"Parsed {len(rows)} of {expected} catalog rows")
    return rows


def translations():
    result = {}
    for line in DATA.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        english, chinese = line.split("\t")
        if english in result or not re.search(r"[\u3400-\u9fff]", chinese):
            raise ValueError(f"Duplicate or untranslated entry: {english}")
        result[english] = chinese
    return result


def render():
    rows = catalog_rows()
    names = translations()
    missing = sorted({r[1] for r in rows} - names.keys())
    if missing:
        raise ValueError(f"Missing Chinese names ({len(missing)}): {missing}")
    lookup = dict(names)
    # Full names take precedence. Ambiguous raw aliases must be fixed explicitly.
    for item_id, name, sprite, category, alias in rows:
        for key in (item_id, alias):
            if not key:
                continue
            if key in lookup and lookup[key] != names[name]:
                raise ValueError(f"Ambiguous alias: {key}")
            lookup[key] = names[name]
    lines = ["// Generated by tools/localization/generate_names.py. Do not edit by hand.",
             "#pragma once", "#include <algorithm>", "#include <iterator>",
             "#include <string_view>", "", "namespace Localization::Names {",
             "struct Entry { std::string_view english; const char* chinese; };",
             "inline constexpr Entry kEntries[] = {"]
    for english, chinese in sorted(lookup.items()):
        lines.append("    {" + json.dumps(english, ensure_ascii=False) + ", "
                     + json.dumps(chinese, ensure_ascii=False) + "},")
    lines += ["};", "", "// Exact matching keeps partial IDs and user labels intact.",
              "inline const char* Lookup(std::string_view name)", "{",
              "    const auto it = std::lower_bound(std::begin(kEntries), std::end(kEntries), name,",
              "        [](const Entry& entry, std::string_view key) { return entry.english < key; });",
              "    return it != std::end(kEntries) && it->english == name ? it->chinese : nullptr;",
              "}", "} // namespace Localization::Names", ""]
    return "\n".join(lines), len(rows), len({r[1] for r in rows}), len(lookup)


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--check", action="store_true")
    check = args.parse_args().check
    content, rows, names, keys = render()
    if check:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != content:
            raise SystemExit("FAIL: LocalizationNames.h is stale; run generate_names.py")
    else:
        HEADER.write_text(content, encoding="utf-8", newline="\n")
    print(f"PASS: {rows} catalog rows, {names} distinct names, {keys} exact names/IDs translated")


if __name__ == "__main__":
    main()
